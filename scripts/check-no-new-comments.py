#!/usr/bin/env python3
import argparse
import os
import re
import subprocess
import sys

DIRECTIVE = re.compile(
    r"^[\s/*#-]*(?:"
    r"!|eslint-|eslint\s|prettier-ignore\b|biome-ignore\b|@ts-|@jsx\b|@flow\b|type:\s*ignore\b|noqa\b|pylint:|pyright:|mypy:|"
    r"ruff:|fmt:|isort:|nosec\b|shellcheck\b|swiftlint:|swiftformat:|ktlint-|detekt\b|nolint\b|noinspection\b|istanbul\b|c8\s|"
    r"coverage:|ignore:|ignore_for_file:|dart format\b|go:(?=[a-z])|\+build\b|coding[:=]|vim:|<auto-generated|<reference\b|"
    r"pragma\b|(?:end)?region\b(?!\s+(?:of|is|in|the|to|for)\b)|frozen_string_literal\b|"
    r"graph:\s*allow-dataclass\s+[\w.-]+|"
    r"SPDX-License-Identifier:|Copyright\b|@license\b"
    r")",
    re.I,
)
HEREDOC = re.compile(r"(?<!<)<<(-?)\s*([\"']?)([A-Za-z_]\w*)\2")

DQ, SQ = ('"', '"', False, True), ("'", "'", False, True)
TRIPLE = (('"""', '"""', True, True), ("'''", "'''", True, True))
C_BLOCK = (("/*", "*/"),)
CS_STRINGS = (('"""', '"""', True, False), ('@"', '"', True, False), DQ, SQ)
LANGS = {}
for exts, line, block, quotes, word_start in (
    ("py pyi", ("#",), (), TRIPLE + (DQ, SQ), False),
    ("sh bash zsh", ("#",), (), (DQ, ("'", "'", False, False)), True),
    ("ts tsx js jsx mjs cjs mts cts", ("//",), C_BLOCK, (DQ, SQ, ("`", "`", True, True)), False),
    ("go", ("//",), C_BLOCK, (DQ, SQ, ("`", "`", True, False)), False),
    ("dart swift kt kts", ("//",), C_BLOCK, TRIPLE + (DQ, SQ), False),
    ("cs", ("//",), C_BLOCK, CS_STRINGS, False),
):
    for ext in exts.split():
        LANGS["." + ext] = {
            "line": line,
            "block": block,
            "quotes": quotes,
            "word_start": word_start,
            "heredoc": ext in ("sh", "bash", "zsh"),
        }


def string_end(text, i, closer, multiline, escapes):
    while i < len(text):
        if escapes and text[i] == "\\":
            i += 2
            continue
        if text.startswith(closer, i):
            return i + len(closer)
        if text[i] == "\n" and not multiline:
            return None
        i += 1
    return None


def token(text, i, spec):
    for mark in spec["line"]:
        if text.startswith(mark, i) and (not spec["word_start"] or i == 0 or text[i - 1] in " \t\n"):
            end = text.find("\n", i)
            return "comment", len(text) if end < 0 else end
    for opener, closer in spec["block"]:
        if text.startswith(opener, i):
            end = text.find(closer, i + len(opener))
            return "comment", len(text) if end < 0 else end + len(closer)
    for opener, closer, multiline, escapes in spec["quotes"]:
        if text.startswith(opener, i):
            end = string_end(text, i + len(opener), closer, multiline, escapes)
            return ("string", end) if end is not None else (None, i + 1)
    return None, i + 1


def heredoc_lines(text):
    skipped, terminator, strip_tabs = set(), None, False
    for number, row in enumerate(text.split("\n"), 1):
        if terminator is not None:
            skipped.add(number)
            if (row.lstrip("\t") if strip_tabs else row) == terminator:
                terminator = None
            continue
        found = HEREDOC.search(row)
        if found:
            strip_tabs, terminator = found.group(1) == "-", found.group(3)
    return skipped


def comment_lines(text, spec, shebang_ok):
    lines, i, line = set(), 0, 1
    while i < len(text):
        kind, end = token(text, i, spec)
        if kind == "comment":
            body = text[i:end]
            allowed = DIRECTIVE.match(body) or (shebang_ok and line == 1 and body.startswith("#!"))
            if not allowed:
                lines.update(range(line, line + body.count("\n") + 1))
        line += text.count("\n", i, end)
        i = end
    return lines - heredoc_lines(text) if spec["heredoc"] else lines


def git(root, *args):
    return subprocess.run(["git", *args], cwd=root, capture_output=True, text=True, check=False)


def repo_root():
    top = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True, check=False)
    if top.returncode != 0:
        print(f"check-no-new-comments: not inside a git repository: {top.stderr.strip()}", file=sys.stderr)
        sys.exit(2)
    return top.stdout.strip()


def added_lines(root, base):
    diff = git(root, "diff", "--merge-base", "--unified=0", "--no-renames", base)
    if diff.returncode != 0:
        print(f"check-no-new-comments: cannot diff against {base}: {diff.stderr.strip()}", file=sys.stderr)
        sys.exit(2)
    added, path = {}, None
    for row in diff.stdout.splitlines():
        if row.startswith("+++ "):
            path = row[6:] if row.startswith("+++ b/") else None
        elif row.startswith("@@") and path:
            m = re.search(r"\+(\d+)(?:,(\d+))?", row)
            start, count = int(m.group(1)), int(m.group(2) or 1)
            added.setdefault(path, set()).update(range(start, start + count))
    return added


def read_text(root, path):
    full = os.path.join(root, path)
    if not os.path.isfile(full):
        return None
    with open(full, "rb") as fh:
        raw = fh.read()
    if b"\0" in raw:
        return None
    return raw.decode("utf-8", errors="replace")


def whole_files(root, paths):
    out = {}
    for path in paths:
        text = read_text(root, path)
        if text is not None:
            out[path] = set(range(1, text.count("\n") + 2))
    return out


def relative_to_root(root, path):
    rel = os.path.relpath(os.path.realpath(os.path.join(os.getcwd(), path)), os.path.realpath(root))
    if rel.startswith(".."):
        print(f"check-no-new-comments: {path} is outside the repository {root}", file=sys.stderr)
        sys.exit(2)
    return rel


def main():
    parser = argparse.ArgumentParser(description="Fail on added comment lines.")
    parser.add_argument("--base", help="ref to diff against (merge base); default HEAD, or whole files when paths are given")
    parser.add_argument("paths", nargs="*", help="limit the scan to these files")
    args = parser.parse_args()
    root = repo_root()
    wanted_paths = [relative_to_root(root, path) for path in args.paths]
    if wanted_paths and args.base is None:
        targets = whole_files(root, wanted_paths)
    else:
        targets = added_lines(root, args.base or "HEAD")
        untracked = git(root, "ls-files", "--others", "--exclude-standard").stdout.split("\n")
        targets.update(whole_files(root, [path for path in untracked if path]))
        if wanted_paths:
            targets = {path: lines for path, lines in targets.items() if path in set(wanted_paths)}
    failed = False
    for path, wanted in sorted(targets.items()):
        spec = LANGS.get(os.path.splitext(path)[1])
        text = read_text(root, path) if spec else None
        if text is None:
            continue
        for number in sorted(wanted & comment_lines(text, spec, True)):
            print(f"{path}:{number}: added code comment")
            failed = True
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
