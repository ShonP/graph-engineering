#!/usr/bin/env python3
import argparse
import os
import re
import subprocess
import sys

DIRECTIVE = re.compile(
    r"^\s*(?:[/*#-]*\s*)?(?:"
    r"!|eslint-|eslint\s|prettier-ignore|biome-ignore|@ts-|@jsx|@flow|type:\s*ignore|noqa|pylint:|pyright:|mypy:|"
    r"ruff:|fmt:|isort:|nosec|shellcheck|swiftlint:|swiftformat:|ktlint-|detekt|nolint|noinspection|istanbul|c8 |"
    r"coverage:|ignore:|ignore_for_file:|dart format|go:|\+build|-\*-|vim:|<auto-generated|<reference|"
    r"pragma|region|endregion|SPDX-License-Identifier|Copyright|@license|frozen_string_literal"
    r")",
    re.I,
)
LICENCE = re.compile(r"SPDX-License-Identifier|Copyright|@license", re.I)

DQ, SQ = ('"', '"', False, True), ("'", "'", False, True)
TRIPLE = (('"""', '"""', True, True), ("'''", "'''", True, True))
C_BLOCK = (("/*", "*/"),)
SLASH = {"line": ("//",), "block": C_BLOCK, "word_start": False}
LANGS = {}
for exts, line, block, quotes, word_start in (
    ("py pyi", ("#",), (), TRIPLE + (DQ, SQ), False),
    ("sh bash zsh", ("#",), (), (DQ, ("'", "'", False, False)), True),
    ("ts tsx js jsx mjs cjs mts cts", ("//",), C_BLOCK, (DQ, SQ, ("`", "`", True, True)), False),
    ("go", ("//",), C_BLOCK, (DQ, SQ, ("`", "`", True, False)), False),
    ("dart swift kt kts", ("//",), C_BLOCK, TRIPLE + (DQ, SQ), False),
    ("cs", ("//",), C_BLOCK, (DQ, SQ), False),
):
    for ext in exts.split():
        LANGS["." + ext] = {"line": line, "block": block, "quotes": quotes, "word_start": word_start}


def string_end(text, i, closer, multiline, escapes):
    while i < len(text):
        if escapes and text[i] == "\\":
            i += 2
            continue
        if text.startswith(closer, i):
            return i + len(closer)
        if text[i] == "\n" and not multiline:
            return None
        i += 1
    return None


def token(text, i, spec):
    for mark in spec["line"]:
        if text.startswith(mark, i) and (not spec["word_start"] or i == 0 or text[i - 1] in " \t\n"):
            end = text.find("\n", i)
            return "comment", len(text) if end < 0 else end
    for opener, closer in spec["block"]:
        if text.startswith(opener, i):
            end = text.find(closer, i + len(opener))
            return "comment", len(text) if end < 0 else end + len(closer)
    for opener, closer, multiline, escapes in spec["quotes"]:
        if text.startswith(opener, i):
            end = string_end(text, i + len(opener), closer, multiline, escapes)
            return ("string", end) if end is not None else (None, i + 1)
    return None, i + 1


def comment_lines(text, spec, shebang_ok):
    lines, i, line = set(), 0, 1
    while i < len(text):
        kind, end = token(text, i, spec)
        if kind == "comment":
            body = text[i:end]
            allowed = DIRECTIVE.match(body.lstrip("/*#- ")) or (shebang_ok and line == 1 and body.startswith("#!"))
            if not allowed and not LICENCE.search(body):
                lines.update(range(line, line + body.count("\n") + 1))
        line += text.count("\n", i, end)
        i = end
    return lines


def git(*args):
    return subprocess.run(["git", *args], capture_output=True, text=True, check=False)


def added_lines(base):
    diff = git("diff", "--merge-base", "--unified=0", "--no-renames", base)
    if diff.returncode != 0:
        print(f"check-no-new-comments: cannot diff against {base}: {diff.stderr.strip()}", file=sys.stderr)
        sys.exit(2)
    added, path = {}, None
    for row in diff.stdout.splitlines():
        if row.startswith("+++ "):
            path = row[6:] if row.startswith("+++ b/") else None
        elif row.startswith("@@") and path:
            m = re.search(r"\+(\d+)(?:,(\d+))?", row)
            start, count = int(m.group(1)), int(m.group(2) or 1)
            added.setdefault(path, set()).update(range(start, start + count))
    return added


def whole_files(paths):
    out = {}
    for path in paths:
        with open(path, encoding="utf-8", errors="replace") as fh:
            out[path] = set(range(1, fh.read().count("\n") + 2))
    return out


def main():
    parser = argparse.ArgumentParser(description="Fail on added comment lines.")
    parser.add_argument("--base", help="ref to diff against (merge base); default HEAD, or whole files when paths are given")
    parser.add_argument("paths", nargs="*", help="limit the scan to these files")
    args = parser.parse_args()
    if args.paths and args.base is None:
        targets = whole_files(args.paths)
    else:
        targets = added_lines(args.base or "HEAD")
        for path in git("ls-files", "--others", "--exclude-standard").stdout.split("\n"):
            if path and os.path.isfile(path):
                targets.update(whole_files([path]))
        if args.paths:
            wanted = {os.path.normpath(path) for path in args.paths}
            targets = {path: lines for path, lines in targets.items() if os.path.normpath(path) in wanted}
    failed = False
    for path, wanted in sorted(targets.items()):
        spec = LANGS.get(os.path.splitext(path)[1])
        if spec is None or not os.path.isfile(path):
            continue
        with open(path, encoding="utf-8", errors="replace") as fh:
            text = fh.read()
        for number in sorted(wanted & comment_lines(text, spec, True)):
            print(f"{path}:{number}: added code comment")
            failed = True
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
